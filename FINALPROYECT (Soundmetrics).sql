CREATE DATABASE soundmetrics;

USE soundmetrics;

-- ENTIDADES PRINCIPALES 

CREATE TABLE markets (
    market_id INT AUTO_INCREMENT PRIMARY KEY,
    market_code VARCHAR(10) NOT NULL UNIQUE,
    market_name VARCHAR(50) NOT NULL
);

CREATE TABLE chart_years (
    year_id INT AUTO_INCREMENT PRIMARY KEY,
    year_value INT NOT NULL UNIQUE
);

CREATE TABLE songs (
    song_id INT AUTO_INCREMENT PRIMARY KEY,
    track_id VARCHAR(100) NOT NULL UNIQUE,
    song_title VARCHAR(255),
    release_date DATE
);

CREATE TABLE artists (
    artist_id INT AUTO_INCREMENT PRIMARY KEY,
    artist_uri VARCHAR(150) UNIQUE,
    artist_name VARCHAR(255)
);

CREATE TABLE song_artists (
    song_id INT,
    artist_id INT,
    PRIMARY KEY (song_id, artist_id),
    FOREIGN KEY (song_id) REFERENCES songs(song_id),
    FOREIGN KEY (artist_id) REFERENCES artists(artist_id)
);

CREATE TABLE charts (
    chart_id INT AUTO_INCREMENT PRIMARY KEY,
    market_id INT NOT NULL,
    year_id INT NOT NULL,
    UNIQUE (market_id, year_id),
    FOREIGN KEY (market_id) REFERENCES markets(market_id),
    FOREIGN KEY (year_id) REFERENCES chart_years(year_id)
);

CREATE TABLE chart_entries (
    entry_id INT AUTO_INCREMENT PRIMARY KEY,
    chart_id INT NOT NULL,
    song_id INT NOT NULL,
    annual_rank INT NOT NULL,
    annual_streams INT NOT NULL,
    weeks_charted INT,
    best_weekly_rank INT,
    UNIQUE (chart_id, song_id),
    UNIQUE (chart_id, annual_rank),
    FOREIGN KEY (chart_id) REFERENCES charts(chart_id),
    FOREIGN KEY (song_id) REFERENCES songs(song_id)
);

